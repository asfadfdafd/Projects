def analyze_case(documents, today=None):
    """Формирует структурированный анализ дела для судьи."""
    extractor = RuleBasedExtractor()
    result = extractor.extract(documents, today=today)
    f = result.features

    claimant_docs = [d for d in documents if d.get("side", "claimant") == "claimant"]
    respondent_docs = [d for d in documents if d.get("side") == "respondent"]

    def side_text(docs):
        raw = "\n\n".join(d.get("text", "") for d in docs)
        return normalize(raw), raw

    cl_norm, cl_raw = side_text(claimant_docs)
    rs_norm, rs_raw = side_text(respondent_docs)

    # --- спорные точки -----------------------------------------------------
    issues = []
    category = f.get("dispute_category")
    for pat in ISSUE_PATTERNS:
        # спорная точка применима не к любой категории: вопрос о приёмке
        # товара бессмыслен в деле о заливе квартиры
        if pat.get("categories") and category not in pat["categories"]:
            continue
        cl_hits = _find_all(cl_norm, cl_raw, pat["triggers"])
        rs_hits = _find_all(rs_norm, rs_raw, pat["triggers"])
        forced = (pat["id"] == "limitation" and not f.get("limitation_period_ok", 1))
        if not (cl_hits or rs_hits or forced):
            continue
        contested = bool(cl_hits and rs_hits) or bool(
            rs_hits and pat["raised_by"] == "respondent")
        issues.append({
            "id": pat["id"],
            "title": pat["title"],
            "gist": pat["gist"],
            "contested": contested,
            "claimant_quote": cl_hits[0] if cl_hits else None,
            "respondent_quote": rs_hits[0] if rs_hits else None,
            "claimant_weak": pat["claimant_weak"],
            "respondent_weak": pat["respondent_weak"],
            "questions": pat["questions"],
        })
    # спорные — вперёд, затем те, что заявлены одной стороной
    issues.sort(key=lambda i: (not i["contested"],))

    # --- карта доказательств по сторонам ----------------------------------
    def evidence_map(docs):
        kinds = {}
        for d in result.documents:
            if d["name"] in [x.get("name") for x in docs]:
                kinds.setdefault(d["kind_label"], 0)
                kinds[d["kind_label"]] += 1
        return [{"kind": k, "count": v} for k, v in sorted(kinds.items())]

    # --- процессуальный чек-лист ------------------------------------------
    checklist = [
        {"item": "Срок исковой давности",
         "status": "warn" if not f.get("limitation_period_ok", 1) else "ok",
         "note": ("Прошло более 3 лет с самой ранней даты в материалах — "
                  "проверить перерыв или восстановление срока."
                  if not f.get("limitation_period_ok", 1)
                  else "По датам в материалах срок не истёк.")},
        {"item": "Досудебный порядок",
         "status": "ok" if f.get("pretrial_claim_sent") else "warn",
         "note": ("Претензия направлена, подтверждение в материалах есть."
                  if f.get("pretrial_claim_sent")
                  else "Сведений о направлении претензии в материалах нет — "
                       "проверить, обязателен ли порядок по договору.")},
        {"item": "Участие ответчика",
         "status": "ok" if respondent_docs else "warn",
         "note": ("Позиция ответчика представлена письменно."
                  if respondent_docs
                  else "Письменной позиции ответчика в материалах нет — "
                       "проверить надлежащее извещение.")},
        {"item": "Представители сторон",
         "status": "ok",
         "note": "Истец: %s. Ответчик: %s." % (
             "с представителем" if f.get("claimant_has_lawyer") else "без представителя",
             "с представителем" if f.get("respondent_has_lawyer") else "без представителя")},
        {"item": "Ходатайства, требующие разрешения",
         "status": "warn" if any(i["id"] in ("expertise_motion", "third_party")
                                 for i in issues) else "ok",
         "note": ("В материалах заявлены ходатайства (экспертиза / привлечение "
                  "третьего лица) — разрешить до рассмотрения по существу."
                  if any(i["id"] in ("expertise_motion", "third_party") for i in issues)
                  else "Неразрешённых ходатайств в материалах не обнаружено.")},
    ]

    # --- расхождения между материалами сторон -------------------------------
    contradictions = find_contradictions(claimant_docs, respondent_docs)

    # --- вопросы сторонам ---------------------------------------------------
    # Вопросы по конкретным расхождениям идут первыми: они точнее и полезнее
    # общих вопросов из каталога.
    questions, seen = [], set()
    for q in contradiction_questions(contradictions):
        seen.add(q)
        questions.append({"question": q, "issue": "Расхождения в материалах",
                          "contested": True})
    for issue in issues:
        for q in issue["questions"]:
            if q in seen:
                continue
            seen.add(q)
            questions.append({"question": q, "issue": issue["title"],
                              "contested": issue["contested"]})
    if not questions:
        questions = [{"question": "Поддерживает ли истец требования в полном "
                                  "объёме?", "issue": "Общие", "contested": False}]

    # --- сценарий заседания -------------------------------------------------
    contested = [i for i in issues if i["contested"]]
    scenario = {
        "focus": ([i["title"] for i in contested] or
                  [i["title"] for i in issues[:2]] or ["Требования не оспорены"]),
        "claimant_line": [i["respondent_weak"] for i in contested[:3]],
        "respondent_line": [i["claimant_weak"] for i in contested[:3]],
        "note": ("Спор сосредоточен на %d вопрос(ах); по остальным "
                 "обстоятельствам расхождений в материалах не выявлено."
                 % len(contested)) if contested else
                ("В материалах не обнаружено письменных возражений по существу "
                 "требований."),
    }

    return {
        "overview": {
            "category": CATEGORIES.get(f.get("dispute_category"), "—"),
            "instance": INSTANCES.get(f.get("court_instance"), "—"),
            "claimant_type": PARTY_TYPES.get(f.get("claimant_type"), "—"),
            "respondent_type": PARTY_TYPES.get(f.get("respondent_type"), "—"),
            "claim_amount": _money(f.get("claim_amount_kzt")),
            "documents_total": len(result.documents),
            "documents_claimant": len(claimant_docs),
            "documents_respondent": len(respondent_docs),
        },
        "documents": result.documents,
        "demands": _extract_demands(claimant_docs),
        "respondent_arguments": _numbered_arguments(respondent_docs),
        "timeline": result.timeline,
        "contradictions": contradictions,
        "issues": issues,
        "checklist": checklist,
        "questions": questions,
        "scenario": scenario,
        "evidence_claimant": evidence_map(claimant_docs),
        "evidence_respondent": evidence_map(respondent_docs),
        "warnings": result.warnings,
        "no_probability_note": (
            "Модуль намеренно не рассчитывает вероятность исхода: такая оценка, "
            "показанная до заседания, влияла бы на внутреннее убеждение суда. "
            "Система показывает состав материалов и спорные точки; выводы по "
            "делу остаются за судьёй."),
    }
