def _find_all(norm, raw, triggers, limit=1):
    hits = []
    for t in triggers:
        p = norm.find(t)
        if p >= 0:
            hits.append(_snippet(raw, p, 190))
            if len(hits) >= limit:
                break
    return hits


def _extract_demands(documents):
    """Блок «ПРОШУ:» из искового заявления."""
    for doc in documents:
        raw = doc.get("text", "")
        norm = normalize(raw)
        p = norm.find("прошу:")
        if p < 0:
            p = norm.find("прошу\n")
        if p < 0:
            continue
        tail = raw[p:p + 900]
        cut = normalize(tail).find("приложени")
        if cut > 0:
            tail = tail[:cut]
        return {"document": doc.get("name"), "text": tail.strip()}
    return None


def _numbered_arguments(documents, limit=6):
    """Пронумерованные доводы из возражений/отзыва ответчика."""
    out = []
    for doc in documents:
        raw = doc.get("text", "")
        for m in re.finditer(r"^\s*(\d)[.)]\s+(.{40,320}?)(?=\n\n|\n\s*\d[.)]|\Z)",
                             raw, re.S | re.M):
            body = " ".join(m.group(2).split())
            if body.lower().startswith(("копия", "выписка", "объяснение")):
                continue          # это список приложений, а не доводы
            out.append({"n": int(m.group(1)), "text": body, "document": doc.get("name")})
            if len(out) >= limit:
                return out
    return out


def _money(v):
    try:
        return "{:,.0f}".format(float(v)).replace(",", " ") + " тг"
    except (TypeError, ValueError):
        return "—"


